// Generates qr-data.js: one QR per slide, each deep-linking to that slide.
// Run from the repo root after changing slide ids or the address:  npm i && npm run qr
const fs = require('fs'), vm = require('vm'), QR = require('qrcode');

const ctx = { window: {} };
vm.createContext(ctx);
vm.runInContext(fs.readFileSync('config.js', 'utf8'), ctx);
vm.runInContext(fs.readFileSync('slides.js', 'utf8'), ctx);
const BASE = ctx.window.ALI_BASE, slides = ctx.window.ALI.slides;

const out = {};
for (const s of slides) {
  const url = BASE + (s.id === 'start' ? '' : '#' + s.id);
  const q = QR.create(url, { errorCorrectionLevel: 'M' });
  const n = q.modules.size, d = q.modules.data;
  let path = '';
  for (let y = 0; y < n; y++) {
    let x = 0;
    while (x < n) {
      if (!d[y * n + x]) { x++; continue; }
      let run = 1;
      while (x + run < n && d[y * n + x + run]) run++;
      path += `M${x} ${y}h${run}v1h-${run}z`;
      x += run;
    }
  }
  out[s.id] = { n, d: path };
}
fs.writeFileSync('qr-data.js', '/* Generated by tools/build-qr.js. Do not edit. */\nwindow.ALI_QR = ' + JSON.stringify(out) + ';\n');
const sizes = [...new Set(Object.values(out).map(q => q.n))].join(', ');
console.log(`qr-data.js: ${slides.length} codes, module size ${sizes}`);
